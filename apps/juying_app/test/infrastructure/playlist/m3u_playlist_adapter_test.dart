import 'dart:convert';

import 'package:flutter_test/flutter_test.dart';
import 'package:http/http.dart' as http;
import 'package:http/testing.dart';
import 'package:juying/application/sources/media_source_registry.dart';
import 'package:juying/domain/models/media_source.dart';
import 'package:juying/domain/models/playlist_source.dart';
import 'package:juying/domain/models/unified_media.dart';
import 'package:juying/infrastructure/playlist/m3u_playlist_adapter.dart';
import 'package:juying/infrastructure/playlist/m3u_playlist_parser.dart';

void main() {
  test('M3U 解析器接收公开 HTTP(S) 频道并保留直播分组', () {
    final channels = M3uPlaylistParser.parse('''
#EXTM3U
#EXTINF:-1 tvg-logo="https://media.example/logo.png" group-title="新闻",官方新闻
https://media.example/live/news.m3u8
#EXTINF:-1 group-title="未知",明文频道
http://media.example/live/insecure.m3u8
''');

    expect(channels, hasLength(2));
    expect(channels.first.name, '官方新闻');
    expect(channels.first.group, '新闻');
    expect(channels.first.logoUri, Uri.parse('https://media.example/logo.png'));
    expect(channels.last.streamUri,
        Uri.parse('http://media.example/live/insecure.m3u8'));
  });

  test('FongMi M3U 允许头部之前存在注释或说明行', () {
    final channels = M3uPlaylistParser.parse('''
# generated by provider
playlist-version=1
#EXTM3U
#EXTINF:-1 group-title="新闻",新闻台
https://media.example/live/news.m3u8
''');

    expect(channels.single.name, '新闻台');
    expect(channels.single.group, '新闻');
  });

  test('IPTV TXT 和分组 JSON 都映射到同一直播模型', () {
    final txt = M3uPlaylistParser.parse('''
新闻,#genre#
新闻一,http://media.example/live/news.m3u8
''');
    final json = M3uPlaylistParser.parse('''
[{"name":"体育","channel":[{"name":"体育一","urls":["https://media.example/live/sports.m3u8\$主线"],"ua":"JuYing-Test"}]}]
''');

    expect(txt.single.group, '新闻');
    expect(
        txt.single.streamUri, Uri.parse('http://media.example/live/news.m3u8'));
    expect(json.single.group, '体育');
    expect(json.single.lineLabels, ['主线']);
    expect(json.single.httpHeaders, {'User-Agent': 'JuYing-Test'});
  });

  test('FongMi JSON 的 pass false 不是密码保护分组', () {
    final channels = M3uPlaylistParser.parse('''
[{"name":"公开频道","pass":false,"channel":[{"name":"直播","urls":["https://media.example/live/open.m3u8"]}]}]
''');

    expect(channels.single.name, '直播');
    expect(channels.single.group, '公开频道');
  });

  test('FongMi M3U 指令、URL 请求头、相对地址和重复频道合并为多线路', () {
    final channels = M3uPlaylistParser.parse(
      '''
#EXTM3U
#EXTINF:-1 http-user-agent="Primary-UA" group-title="新闻",新闻台
#EXTVLCOPT:http-referrer=https://portal.example/
live/main.m3u8|Origin=https%3A%2F%2Fportal.example
#EXTINF:-1 group-title="新闻",新闻台
#EXTHTTP:{"User-Agent":"Backup-UA"}
https://backup.example/live.m3u8
''',
      baseUri: Uri.parse('https://playlist.example/path/list.m3u'),
    );

    expect(channels, hasLength(1));
    expect(channels.single.streamUri,
        Uri.parse('https://playlist.example/path/live/main.m3u8'));
    expect(channels.single.alternateStreamUris,
        [Uri.parse('https://backup.example/live.m3u8')]);
    expect(channels.single.httpHeaders, {
      'User-Agent': 'Primary-UA',
      'Referer': 'https://portal.example/',
      'Origin': 'https://portal.example',
    });
    expect(channels.single.alternateHttpHeaders.single,
        {'User-Agent': 'Backup-UA'});
  });

  test('FongMi TXT 分组指令和井号分隔的多线路可直接播放', () {
    final channel = M3uPlaylistParser.parse('''
新闻,#genre#
ua=LivingRoom
referer=https://portal.example/
新闻台,https://one.example/live.m3u8\$主线#https://two.example/live.m3u8\$备用
''').single;

    expect(channel.lineLabels, ['主线', '备用']);
    expect(channel.httpHeaders, {
      'User-Agent': 'LivingRoom',
      'Referer': 'https://portal.example/',
    });
    expect(channel.alternateHttpHeaders.single, channel.httpHeaders);
  });

  test('用户授权清单通过统一适配器产生直播目录、搜索和播放描述', () async {
    final adapter = M3uPlaylistAdapter(
      definition: _definition,
      client: MockClient((request) async {
        expect(request.url, _definition.playlistUri);
        return http.Response(
            '''
#EXTM3U
#EXTINF:-1 group-title="纪录片" homepage="https://official.example/channel",自然直播
https://stream.example/live/nature.m3u8
''',
            200,
            headers: {'content-type': 'text/plain; charset=utf-8'});
      }),
    );
    final registry = MediaSourceRegistry([]);
    expect(registry.register(adapter), isTrue);
    final managed = registry[_definition.id]!;

    final page = await managed.browse(
      const MediaCatalogQuery(category: MediaCategory.live),
    );
    final item = page.items.single;
    final hits = await managed.search('自然');
    final episode = (await managed.episodes(item)).single;
    final playback = await managed.resolvePlayback(episode);

    expect(item.id, startsWith('${_definition.id}:'));
    expect(item.category, MediaCategory.live);
    expect(hits.single.item.id, item.id);
    expect(playback.sourceId, _definition.id);
    expect(
      playback.nativeStreamUri,
      Uri.parse('https://stream.example/live/nature.m3u8'),
    );
    expect(
      playback.officialPageUri,
      Uri.parse('https://official.example/channel'),
    );
  });

  test('分组 JSON 清单的备用线路可传递到统一播放器', () async {
    final adapter = M3uPlaylistAdapter(
      definition: _definition,
      client: MockClient((_) async => http.Response.bytes(
            utf8.encode(
              '[{"name":"新闻","channel":[{"name":"直播","urls":["https://media.example/live/a.m3u8\$主线","https://media.example/live/b.m3u8\$备用"]}]}]',
            ),
            200,
          )),
    );

    final item = (await adapter
            .browse(const MediaCatalogQuery(category: MediaCategory.live)))
        .items
        .single;
    final playback =
        await adapter.resolvePlayback((await adapter.episodes(item)).single);

    expect(adapter.source.capabilities,
        contains(SourceCapability.qualitySelection));
    expect(playback.qualityOptions.map((line) => line.label), ['主线', '备用']);
    expect(playback.qualityOptions.last.streamUri,
        Uri.parse('https://media.example/live/b.m3u8'));
  });

  test('非直播分类为空，重复运行时来源不会覆盖已有适配器', () async {
    final adapter = M3uPlaylistAdapter(
      definition: _definition,
      client: MockClient((_) async => http.Response('#EXTM3U\n', 200)),
    );
    final registry = MediaSourceRegistry([adapter]);

    final page = await registry[_definition.id]!.browse(
      const MediaCatalogQuery(category: MediaCategory.movie),
    );
    expect(page.items, isEmpty);
    expect(registry.register(adapter), isFalse);
    expect(registry.unregister(_definition.id), isTrue);
    expect(registry[_definition.id], isNull);
  });
}

final _definition = PlaylistSourceDefinition(
  id: 'playlist-family-live',
  name: '家庭直播',
  playlistUri: Uri.parse('https://playlist.example/family.m3u'),
  rightsConfirmedAt: DateTime.utc(2025, 8, 20),
);
